// Bundles facts/*.md into src/facts.generated.ts so the same code runs on Node and Cloudflare Workers.
// Each facts file: YAML-ish front matter (game, aliases, version, verified_by) + markdown body.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "facts");
const out = [];
if (existsSync(dir)) {
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".md") && !f.startsWith("_"))) {
    const raw = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!m) throw new Error(`${f}: missing front matter`);
    const meta = {};
    for (const line of m[1].split("\n")) {
      const kv = line.match(/^(\w+):\s*(.*)$/);
      if (kv) meta[kv[1]] = kv[2].trim();
    }
    if (!meta.game) throw new Error(`${f}: front matter needs game:`);
    out.push({
      file: f,
      game: meta.game,
      aliases: (meta.aliases ?? "").split(",").map((s) => s.trim()).filter(Boolean),
      version: meta.version ?? "unknown",
      verified: meta.verified ?? "",
      body: m[2].trim(),
    });
  }
}
writeFileSync(
  join(root, "src", "facts.generated.ts"),
  `// GENERATED by scripts/build-facts.mjs from facts/*.md. Do not edit.\nexport const FACTS: { file: string; game: string; aliases: string[]; version: string; verified: string; body: string }[] = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`facts: bundled ${out.length} file(s)`);
